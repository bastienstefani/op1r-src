#!/usr/bin/env python3
"""Generate drive_tables.h for the drive FX (all values are our own maths, nothing from the firmware).

    python3 plugins/drive/gen_drive_tables.py > plugins/drive/drive_tables.h
"""
import math

N = 33                                              # 32 segments, linear interpolation in between


def tab(f):
    return [round(f(i / (N - 1))) for i in range(N)]


def fc(v):                                          # filter cutoff, 30 Hz .. 10 kHz, exponential
    return 30 * (10000 / 30) ** v


def pade(t):                                        # tanh(t) as x (27 + x^2) / (27 + 9 x^2): exactly 1.0 at t = 3
    return t * (27 + t * t) / (27 + 9 * t * t)


TABLES = [
    ('SINQ', 'sin(pi/2 * i/256) in Q15, quarter wave', [round(32767 * math.sin(math.pi / 2 * i / 256)) for i in range(257)]),
    ('DRIVE_Q8', 'drive gain 1x .. 40x (0 .. 32 dB), Q8', tab(lambda v: 256 * 40 ** v)),
    ('SVF_F_Q14', 'state-variable filter coefficient 2 sin(pi fc / 88200) at 2x oversampling, Q14', tab(lambda v: 16384 * 2 * math.sin(math.pi * fc(v) / 88200))),
    ('FC_HZ', 'cutoff in Hz, for the screen', tab(fc)),
    ('LEVEL_Q12', 'output level -24 .. +6 dB, Q12', tab(lambda v: 4096 * 10 ** ((-24 + 30 * v) / 20))),
    ('DS_N', 'downsample hold length 1 .. 64 samples', tab(lambda v: 64 ** v)),
    # the soft shapers without a division per sample: |x| in Q15, step 512 (1/64), linear interpolation
    ('TANH_Q15', 'tanh (Pade, 1.0 from x = 3) of i/64, Q15, i = 0..193', [min(32767, round(32768 * pade(min(i / 64, 3)))) for i in range(194)]),
    ('HYP_Q15', 'x / (1 + x) of x = i/64, Q15, i = 0..1025', [min(32767, round(32768 * (i / 64) / (1 + i / 64))) for i in range(1026)]),
]

print('/* Generated by gen_drive_tables.py - do not edit. */')
for name, doc, t in TABLES:
    ty = 'int16_t' if max(t) < 32768 else 'int32_t'
    print(f'/* {doc} */')
    print(f'static const {ty} {name}[{len(t)}] = {{')
    for i in range(0, len(t), 12):
        print('    ' + ', '.join(f'{x:5d}' for x in t[i:i + 12]) + ',')
    print('};')
