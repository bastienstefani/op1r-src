#!/usr/bin/env python3
"""Generate display/roll.svg + seq/roll_geom.h (screen of the roll piano-roll sequencer, seq/roll.c).

Static: a thin line under the header. Code draws the grid (it follows the grid setting and the cursor's page), the
C rows and their labels, the notes, the cursor, the playhead, the loop end and all text. Visible area ends ~y 140
(as euclid.svg): 16 rows of 7.5 px from y 20.
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
DIM = '#4A4C4E'
BLUE, GREEN, WHITE, RED, GREY = '#4D9EFF', '#00ED95', '#FFFFFF', '#FF3A5D', '#6F7173'
GRID_X0, GRID_X1, GRID_Y0, ROW_H = 18, 316, 20, 7.5  # note grid: 16 columns x 16 rows
HEAD_Y = 4.5                                         # header text top
GRID_TX, LEN_TX, VEL_TX, LOOP_TX = 4, 46, 116, 178   # header: grid, length, velocity, loop
BOX_X0, BOX_X1, BOX_Y0, BOX_Y1 = 268, 314, 2, 15.5   # play / hold box

def svg():
    return '\n'.join(['<?xml version="1.0" encoding="utf-8"?>',
        '<svg version="1.1" id="Layer_1" xmlns="http://www.w3.org/2000/svg" x="0px" y="0px"',
        '\t width="320px" height="160px" viewBox="0 0 320 160">',
        '<!-- generated by display/gen_roll_svg.py - roll sequencer: header line; grid, notes and text drawn by code -->',
        f'<line fill="none" stroke="{DIM}" stroke-width="1" x1="4" y1="{BOX_Y1 + 1.5}" x2="{BOX_X1}" y2="{BOX_Y1 + 1.5}"/>',
        '</svg>']) + '\n'

def header():
    rgb = lambda c, f=1.0: '{ %d, %d, %d, 255 }' % tuple(int(int(c[i:i + 2], 16) * f) for i in (1, 3, 5))
    return '\n'.join(['/* generated by display/gen_roll_svg.py - geometry of display/roll.svg */',
        f'#define RL_GRID_X0 {GRID_X0}', f'#define RL_GRID_X1 {GRID_X1}', f'#define RL_GRID_Y0 {GRID_Y0}',
        f'#define RL_ROW_H {ROW_H}', f'#define RL_HEAD_Y {HEAD_Y}',
        f'#define RL_GRID_TX {GRID_TX}', f'#define RL_LEN_TX {LEN_TX}', f'#define RL_VEL_TX {VEL_TX}',
        f'#define RL_LOOP_TX {LOOP_TX}',
        f'#define RL_BOX_X0 {BOX_X0}', f'#define RL_BOX_X1 {BOX_X1}', f'#define RL_BOX_Y0 {BOX_Y0}', f'#define RL_BOX_Y1 {BOX_Y1}',
        'static const uint8_t rl_blue[4] = ' + rgb(BLUE) + ';',
        'static const uint8_t rl_green[4] = ' + rgb(GREEN) + ';',
        'static const uint8_t rl_cline[4] = ' + rgb(GREEN, 0.35) + ';',
        'static const uint8_t rl_white[4] = ' + rgb(WHITE) + ';',
        'static const uint8_t rl_red[4] = ' + rgb(RED) + ';',
        'static const uint8_t rl_dimred[4] = ' + rgb(RED, 0.4) + ';',
        'static const uint8_t rl_grey[4] = ' + rgb(GREY, 1.4) + ';',
        'static const uint8_t rl_dim[4] = ' + rgb(GREY) + ';']) + '\n'

if __name__ == '__main__':
    open(os.path.join(HERE, 'roll.svg'), 'w', newline='\n').write(svg())         # LF on Windows too
    open(os.path.join(os.path.dirname(HERE), 'seq', 'roll_geom.h'), 'w', newline='\n').write(header())
    print('ok')
